import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats

y = np.array([
    7.5, 12.3, 13.5, 9.0, 14.2, 9.4, 13.5, 8.7, 8.0, 7.6,
    12.8, 10.9, 15.2, 9.3, 11.9, 9.8, 9.9, 9.0, 14.2, 14.3,
    14.1, 12.9, 12.1, 10.4, 10.9, 12.2, 16.1, 11.0, 10.1, 12.0,
    14.0, 12.9, 10.1, 18.5, 19.4, 12.1, 11.6, 10.8, 19.7, 17.2,
    7.0, 11.3, 16.1, 12.0, 12.7, 8.5, 11.9, 12.6, 12.6, 14.9,
    12.1, 16.6, 8.3, 12.1, 11.7, 20.7, 16.9, 17.5, 17.0, 18.0,
    16.7, 18.6, 14.1, 15.2, 12.0, 16.4, 17.4, 17.0, 14.7, 13.2,
    14.0, 12.1, 9.1, 21.4
])

x = np.array([
    9042, 2199, 2627, 14770, 1819, 15519, 3163, 5565, 6524, 30023,
    1343, 2751, 12633, 16665, 7044, 9695, 3767, 24433, 2045, 1798,
    1245, 2204, 6761, 21244, 4204, 2402, 2896, 2302, 9086, 12308,
    4525, 9467, 892, 919, 384, 1966, 8349, 14452, 1202, 4087,
    7972, 2053, 8368, 9244, 2916, 7715, 3671, 5693, 13760, 9934,
    4258, 1978, 6246, 31742, 8339, 479, 1019, 1719, 10035, 1209,
    9086, 3949, 7424, 14134, 9701, 4512, 731, 3818, 10008, 8879,
    4335, 648, 1900, 195
])

n = len(x)
print("=" * 60)

# ============================================================================
# 1. ПОСТРОИТЬ ПОЛЕ КОРРЕЛЯЦИИ И ГИПОТЕЗА О ФОРМЕ СВЯЗИ
# ============================================================================
plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='blue', s=50, alpha=0.6, edgecolors='black')
plt.title('Поле корреляции: Зависимость уровня бедности (y) от миграции (x)')
plt.xlabel('Число прибывших (x)')
plt.ylabel('Доля населения с доходами ниже минимума (y), %')
plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()

print("\n1. ГИПОТЕЗА О ФОРМЕ СВЯЗИ:")
print("   По графику видно распределение точек.")
print("   Гипотеза: Между переменными существует ЛИНЕЙНАЯ связь.")
print("-" * 60)

# ============================================================================
# 2. ПАРАМЕТРЫ УРАВНЕНИЯ РЕГРЕССИИ
# ============================================================================
res = stats.linregress(x, y)

b = res.slope      # Коэффициент регрессии (наклон)
a = res.intercept  # Свободный член

print("\n2. УРАВНЕНИЕ РЕГРЕССИИ:")
print(f"   Коэффициент b (наклон): {b:.6f}")
print(f"   Коэффициент a (сдвиг):  {a:.6f}")
print(f"   Уравнение в явном виде: y = {a:.2f} {'+' if b < 0 else '-'} {abs(b):.4f} * x")

print("\n   ВЫВОД по коэффициенту b:")
if b < 0:
    print(f"   Так как b < 0 ({b:.6f}), связь отрицательная.")
    print(f"   При увеличении числа прибывших на 1000 человек, доля бедных снижается в среднем на {abs(b)*1000:.2f}% (п.п.).")
elif b > 0:
    print(f"   Так как b > 0 ({b:.6f}), связь положительная.")
    print(f"   При увеличении числа прибывших на 1000 человек, доля бедных растёт в среднем на {b*1000:.2f}% (п.п.).")
else:
    print(f"   Коэффициент b ≈ 0, связь отсутствует.")
print("-" * 60)

# ============================================================================
# 3. КОЭФФИЦИЕНТ ЛИНЕЙНОЙ КОРРЕЛЯЦИИ
# ============================================================================
r = res.rvalue
r_squared = r ** 2

print("\n3. КОЭФФИЦИЕНТ ЛИНЕЙНОЙ КОРРЕЛЯЦИИ:")
print(f"   Коэффициент Пирсона (r): {r:.4f}")
print(f"   Коэффициент детерминации (R²): {r_squared:.4f}")

# Оценка силы связи
if abs(r) >= 0.7:
    strength = "сильная"
elif abs(r) >= 0.3:
    strength = "умеренная"
else:
    strength = "слабая"

direction = "отрицательная" if r < 0 else "положительная"
print(f"   Вывод: Наблюдается {strength} {direction} линейная связь.")
print(f"   R² = {r_squared:.4f} означает, что вариация миграции объясняет {r_squared*100:.2f}% вариации уровня бедности.")
print("-" * 60)

# ============================================================================
# 4. F-КРИТЕРИЙ ФИШЕРА
# ============================================================================
alpha = 0.05  # Уровень значимости

# Расчет F-статистики через R²
F_calc = (r_squared / 1) / ((1 - r_squared) / (n - 2))

# Критическое значение F (распределение Фишера)
F_crit = stats.f.ppf(1 - alpha, 1, n - 2)

print("\n4. ОЦЕНКА УРАВНЕНИЯ РЕГРЕССИИ (F-критерий Фишера):")
print(f"   Фактическое значение F (F_расч): {F_calc:.4f}")
print(f"   Критическое значение F (F_кр) при α=0.05: {F_crit:.4f}")
print(f"   Степени свободы: df1=1, df2={n-2}")

print("\n   ВЫВОД:")
if F_calc > F_crit:
    print("   F_расч > F_кр => Уравнение регрессии СТАТИСТИЧЕСКИ ЗНАЧИМО.")
    print("   Нулевая гипотеза об отсутствии связи отвергается.")
else:
    print("   ✗ F_расч < F_кр => Уравнение регрессии НЕ ЗНАЧИМО.")
    print("   Линейная связь статистически не подтверждается.")

print("=" * 60)
