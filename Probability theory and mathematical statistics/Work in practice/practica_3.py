df = pd.DataFrame(data)
x = np.array(df['x'], dtype=float)
y = np.array(df['y'], dtype=float)
n = len(x)

print("=" * 70)
print("КОРРЕЛЯЦИОННО-РЕГРЕССИОННЫЙ АНАЛИЗ ПО РЕГИОНАМ РФ")
