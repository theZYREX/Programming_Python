# ============================================================================
# 1. ПОЛЕ КОРРЕЛЯЦИИ И ГИПОТЕЗА О ФОРМЕ СВЯЗИ
# ============================================================================
print("1. ПОЛЕ КОРРЕЛЯЦИИ")
print("-" * 70)

plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='steelblue', s=40, alpha=0.7, edgecolors='black', linewidth=0.5)
plt.xlabel('Факторный признак (x)', fontsize=11)
plt.ylabel('Результативный признак (y)', fontsize=11)
plt.title('Поле корреляции', fontsize=13, fontweight='bold')
plt.grid(True, alpha=0.3, linestyle='--')
plt.tight_layout()
plt.show()

print("Гипотеза о форме связи:")
print("→ На основе визуального анализа предполагается ЛИНЕЙНАЯ связь между x и y.")
print()

# ============================================================================
# 2. ПАРАМЕТРЫ ЛИНЕЙНОЙ РЕГРЕССИИ
# ============================================================================
print("2. УРАВНЕНИЕ ЛИНЕЙНОЙ РЕГРЕССИИ")
print("-" * 70)

x_mean, y_mean = np.mean(x), np.mean(y)
numerator = np.sum((x - x_mean) * (y - y_mean))
denominator = np.sum((x - x_mean) ** 2)

b = numerator / denominator
a = y_mean - b * x_mean

print(f"Коэффициент регрессии b = {b:.8f}")
print(f"Свободный член a = {a:.4f}")
print(f"Уравнение регрессии: y = {a:.4f} {'+' if b >= 0 else '-'} {abs(b):.8f} * x")

y_pred = a + b * x
plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='steelblue', s=40, alpha=0.6, label='Эмпирические данные')
plt.plot(x, y_pred, color='red', linewidth=2, label=f'Линия регрессии: y = {a:.2f} {b:+.2e}x')
plt.xlabel('Факторный признак (x)')
plt.ylabel('Результативный признак (y)')
plt.title('Линейная регрессия')
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ============================================================================
# 3. КОЭФФИЦИЕНТЫ КОРРЕЛЯЦИИ И ДЕТЕРМИНАЦИИ
# ============================================================================
print("3. ОЦЕНКА ТЕСНОТЫ СВЯЗИ")
print("-" * 70)

r = numerator / np.sqrt(denominator * np.sum((y - y_mean) ** 2))
r_squared = r ** 2

print(f"Линейный коэффициент корреляции Пирсона: r = {r:.4f}")
print(f"Коэффициент детерминации: R² = {r_squared:.4f} ({r_squared*100:.2f}%)")

if abs(r) >= 0.7:
    strength = "сильная"
elif abs(r) >= 0.3:
    strength = "умеренная"
else:
    strength = "слабая"
direction = "прямая" if r > 0 else "обратная"

print(f"\nВывод: Наблюдается {strength} {direction} линейная связь.")
print(f"R² показывает, что {r_squared*100:.2f}% вариации y объясняется вариацией x.")
print()

# ============================================================================
# 4. КОЭФФИЦИЕНТ ЭЛАСТИЧНОСТИ
# ============================================================================
print("4. КОЭФФИЦИЕНТ ЭЛАСТИЧНОСТИ")
print("-" * 70)

elasticity = b * (x_mean / y_mean)

print(f"Коэффициент эластичности: Ē = {elasticity:.6f}")
print(f"\nВывод:")
if abs(elasticity) > 1:
    print(f"  • |Ē| > 1 → результативный признак y ЭЛАСТИЧЕН по фактору x")
    print(f"    Изменение x на 1% вызывает изменение y на {abs(elasticity):.2f}%")
elif abs(elasticity) < 1:
    print(f"  • |Ē| < 1 → результативный признак y НЕЭЛАСТИЧЕН по фактору x")
    print(f"    Изменение x на 1% вызывает изменение y на {abs(elasticity):.2f}%")
else:
    print(f"  • |Ē| ≈ 1 → единичная эластичность")
print()

# ============================================================================
# 5. ОЦЕНКА ЗНАЧИМОСТИ ПАРАМЕТРОВ (t-критерий Стьюдента)
# ============================================================================
print("5. ЗНАЧИМОСТЬ ПАРАМЕТРОВ РЕГРЕССИИ (t-критерий)")
print("-" * 70)

SS_res = np.sum((y - y_pred) ** 2)
s_e = np.sqrt(SS_res / (n - 2))

s_b = s_e / np.sqrt(denominator)
s_a = s_e * np.sqrt(1/n + x_mean**2 / denominator)

t_b = b / s_b
t_a = a / s_a

alpha = 0.05
df = n - 2
t_crit = stats.t.ppf(1 - alpha/2, df)

print(f"Стандартная ошибка оценки: sₑ = {s_e:.4f}")
print(f"\nДля коэффициента b:")
print(f"  • Стандартная ошибка: s_b = {s_b:.2e}")
print(f"  • t-статистика: t_b = {t_b:.4f}")
print(f"  • Критическое значение: t_кр = {t_crit:.4f}")
print(f"  • Результат: {' ЗНАЧИМ' if abs(t_b) > t_crit else ' НЕ ЗНАЧИМ'}")

print(f"\nДля коэффициента a:")
print(f"  • Стандартная ошибка: s_a = {s_a:.2e}")
print(f"  • t-статистика: t_a = {t_a:.4f}")
print(f"  • Результат: {'ЗНАЧИМ' if abs(t_a) > t_crit else ' НЕ ЗНАЧИМ'}")

print(f"\nДоверительные интервалы (α = 0.05):")
print(f"  • Для b: [{b - t_crit*s_b:.2e}; {b + t_crit*s_b:.2e}]")
print(f"  • Для a: [{a - t_crit*s_a:.4f}; {a + t_crit*s_a:.4f}]")
print()

# ============================================================================
# 6. F-КРИТЕРИЙ ФИШЕРА
# ============================================================================
print("6. ОЦЕНКА УРАВНЕНИЯ РЕГРЕССИИ (F-критерий Фишера)")
print("-" * 70)

F_calc = (r_squared / 1) / ((1 - r_squared) / (n - 2))
F_crit = stats.f.ppf(1 - alpha, 1, n - 2)
p_value = 1 - stats.f.cdf(F_calc, 1, n - 2)

print(f"Фактическое значение F: F_расч = {F_calc:.4f}")
print(f"Критическое значение F: F_кр = {F_crit:.4f} (α=0.05, df1=1, df2={n-2})")
print(f"P-value: {p_value:.6f}")

print(f"\nВывод:")
if F_calc > F_crit:
    print("  F_расч > F_кр → уравнение регрессии СТАТИСТИЧЕСКИ ЗНАЧИМО")
    print("  Линейная связь между x и y подтверждается на уровне α = 0.05")
else:
    print(" F_расч < F_кр → уравнение регрессии НЕ ЗНАЧИМО")
    print(" Линейная модель не адекватна данным")
print()

# ============================================================================
# 7. НЕЛИНЕЙНЫЕ МОДЕЛИ
# ============================================================================
print("7. ПОСТРОЕНИЕ НЕЛИНЕЙНЫХ МОДЕЛЕЙ")
print("-" * 70)

def hyperbolic(x, a, b):
    return a + b / x

def power(x, a, b):
    return a * (x ** b)

def exponential(x, a, b):
    return a * np.exp(b * x)

models = {}
results = []

try:
    popt_h, _ = curve_fit(hyperbolic, x, y, maxfev=5000, p0=[100, 10000])
    y_hyp = hyperbolic(x, *popt_h)
    r2_hyp = 1 - np.sum((y - y_hyp)**2) / np.sum((y - y_mean)**2)
    models['hyperbolic'] = {'func': hyperbolic, 'params': popt_h, 'r2': r2_hyp, 'y_pred': y_hyp}
    results.append(('Гиперболическая', f"y = {popt_h[0]:.4f} + {popt_h[1]:.2f}/x", r2_hyp))
    print(f" Гиперболическая: y = {popt_h[0]:.4f} + {popt_h[1]:.2f}/x, R² = {r2_hyp:.4f}")
except:
    print(" Гиперболическая модель: не удалось подобрать параметры")

try:
    mask = x > 0
    popt_p, _ = curve_fit(power, x[mask], y[mask], maxfev=5000, p0=[100, 0.01])
    y_pow = power(x, *popt_p)
    r2_pow = 1 - np.sum((y[mask] - y_pow[mask])**2) / np.sum((y[mask] - y_mean)**2)
    models['power'] = {'func': power, 'params': popt_p, 'r2': r2_pow, 'y_pred': y_pow}
    results.append(('Степенная', f"y = {popt_p[0]:.4f} * x^{popt_p[1]:.4f}", r2_pow))
    print(f" Степенная: y = {popt_p[0]:.4f} * x^{popt_p[1]:.4f}, R² = {r2_pow:.4f}")
except:
    print(" Степенная модель: не удалось подобрать параметры")

try:
    popt_e, _ = curve_fit(exponential, x, y, maxfev=5000, p0=[100, 1e-7])
    y_exp = exponential(x, *popt_e)
    r2_exp = 1 - np.sum((y - y_exp)**2) / np.sum((y - y_mean)**2)
    models['exponential'] = {'func': exponential, 'params': popt_e, 'r2': r2_exp, 'y_pred': y_exp}
    results.append(('Показательная', f"y = {popt_e[0]:.4f} * exp({popt_e[1]:.2e} * x)", r2_exp))
    print(f" Показательная: y = {popt_e[0]:.4f} * exp({popt_e[1]:.2e} * x), R² = {r2_exp:.4f}")
except:
    print(" Показательная модель: не удалось подобрать параметры")

results.append(('Линейная', f"y = {a:.4f} {b:+.2e} * x", r_squared))

print()

