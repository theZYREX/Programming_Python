print(f"Среднее значение фактора: x̄ = {x_avg:,.0f}")
print(f"Прогнозное значение: xₚᵣₒg = {x_avg:,.0f} × 1.15 = {x_forecast:,.0f}")

if best_model == 'Линейная':
    y_forecast = a + b * x_forecast
    model_used = "линейная"
elif best_model == 'Гиперболическая' and 'hyperbolic' in models:
    y_forecast = hyperbolic(x_forecast, *models['hyperbolic']['params'])
    model_used = "гиперболическая"
elif best_model == 'Степенная' and 'power' in models:
    y_forecast = power(x_forecast, *models['power']['params'])
    model_used = "степенная"
elif best_model == 'Показательная' and 'exponential' in models:
    y_forecast = exponential(x_forecast, *models['exponential']['params'])
    model_used = "показательная"
else:
    y_forecast = a + b * x_forecast
    model_used = "линейная (резервная)"

print(f"\nПрогнозное значение результативного признака:")
print(f"  ŷ = {y_forecast:.4f} (по {model_used} модели)")

y_avg = np.mean(y)
change_pct = (y_forecast - y_avg) / y_avg * 100
print(f"\nИнтерпретация:")
print(f"  • При увеличении фактора на 15% (с {x_avg:,.0f} до {x_forecast:,.0f})")
print(f"  • Результативный признак изменится с {y_avg:.4f} до {y_forecast:.4f}")
print(f"  • Относительное изменение: {change_pct:+.2f}%")
print()

