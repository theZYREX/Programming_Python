results_sorted = sorted(results, key=lambda x: x[2], reverse=True)

print("Ранжирование моделей по коэффициенту детерминации R²:")
for i, (name, equation, r2) in enumerate(results_sorted, 1):
    marker = "ЛУЧШАЯ" if i == 1 else ""
    print(f"{i}. {name:15s} | R² = {r2:.4f} | {equation} {marker}")

best_model = results_sorted[0][0]
print(f"\n Лучшая модель: {best_model}")
print()

