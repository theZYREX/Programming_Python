# -----------------------------------------------------------------------------------------------------------------------------------
# ЗАДАЧА 1

"""
Случайная величина X задана интегральной функцией:

        | 0,           при x ≤ 0
F(x) =  | x²/4,        при 0 < x ≤ 2
        | 1,           при x > 2

ТРЕБУЕТСЯ:
а) Найти дифференциальную функцию (плотность вероятности) f(x)
б) Найти математическое ожидание M[X] и дисперсию D[X]
в) Построить графики F(x) и f(x)
"""

# -----------------------------------------------------------------------------------------------------------------------------------
# а) Находим дифференциальную функцию (плотность вероятности)
# f(x) = F'(x) = d/dx (x²/4) = x/2  при 0 < x ≤ 2
# -----------------------------------------------------------------------------------------------------------------------------------

def f1(x):
    """Плотность вероятности"""
    result = np.zeros_like(x, dtype=float)
    mask = (x > 0) & (x <= 2)
    result[mask] = x[mask] / 2
    return result

def F1(x):
    """Интегральная функция для задачи 1"""
    result = np.zeros_like(x, dtype=float)
    mask1 = (x > 0) & (x <= 2)
    mask2 = x > 2
    result[mask1] = (x[mask1] ** 2) / 4
    result[mask2] = 1
    return result

# -----------------------------------------------------------------------------------------------------------------------------------
# б) Находим математическое ожидание и дисперсию
# -----------------------------------------------------------------------------------------------------------------------------------

def integrand_expectation(x):
    return x * (x / 2)  # x * f1(x) для 0 < x ≤ 2

expectation, _ = quad(integrand_expectation, 0, 2)

def integrand_variance(x):
    return (x ** 2) * (x / 2)  # x² * f1(x) для 0 < x ≤ 2

expectation_x2, _ = quad(integrand_variance, 0, 2)

variance = expectation_x2 - expectation ** 2

print(f"Задача 1:")
print(f"а) Плотность вероятности: f(x) = x/2 при 0 < x ≤ 2, иначе 0")
print(f"б) Математическое ожидание: M[X] = {expectation:.5f}")
print(f"   Дисперсия: D[X] = {variance:.5f}")

