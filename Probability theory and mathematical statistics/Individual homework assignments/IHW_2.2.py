# ЗАДАЧА 2

"""
Случайная величина X задана дифференциальной функцией:

        | 0,                  при x ≤ 0
f(x) =  | 0.5·sin(x),         при 0 < x ≤ π
        | 0,                  при x > π

ТРЕБУЕТСЯ:
а) Найти интегральную функцию F(x)
б) Найти вероятность попадания случайной величины в интервал (0, π/4)
"""

# -----------------------------------------------------------------------------------------------------------------------------------
# а) Находим интегральную функцию
# F(x) = ∫ f(t) dt от -∞ до x
# При 0 < x ≤ π: F(x) = ∫₀ˣ 0.5·sin(t) dt = 0.5·(1 - cos(x))
# -----------------------------------------------------------------------------------------------------------------------------------

def f2(x):
    """Плотность вероятности для задачи 2"""
    result = np.zeros_like(x, dtype=float)
    mask = (x > 0) & (x <= np.pi)
    result[mask] = 0.5 * np.sin(x[mask])
    return result

def F2(x):
    """Интегральная функция для задачи 2"""
    result = np.zeros_like(x, dtype=float)
    mask1 = (x > 0) & (x <= np.pi)
    mask2 = x > np.pi
    result[mask1] = 0.5 * (1 - np.cos(x[mask1]))
    result[mask2] = 1
    return result

print(f"\nЗадача 2:")
print(f"а) Интегральная функция:")
print(f"        | 0 при x ≤ 0")
print(f"   F(x)=| 0.5(1 - cos(x)) при 0 < x ≤ π")
print(f"        | 1 при x > π")

# -----------------------------------------------------------------------------------------------------------------------------------
# б) Вероятность попадания в интервал (0, π/4)
# P(a < X < b) = F(b) - F(a)
# -----------------------------------------------------------------------------------------------------------------------------------

a = 0
b = np.pi / 4

probability = F2(np.array([b]))[0] - F2(np.array([a]))[0]

print(f"\nб) Вероятность P(0 < X < π/4) = {probability:.5f}")
print(f"   Аналитически: 0.5(1 - cos(π/4)) = {0.5 * (1 - np.cos(np.pi/4)):.5f}")


# -----------------------------------------------------------------------------------------------------------------------------------
# Построение графика для 1 задачи пункт "в"
# -----------------------------------------------------------------------------------------------------------------------------------

x_vals = np.linspace(-1, 3, 1000)
F_vals = F1(x_vals)
f_vals = f1(x_vals)

plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
