plt.subplot(1, 2, 2)
plt.plot(x_vals, f_vals, 'r-', linewidth=2, label='f(x)')
plt.axvline(x=0, color='gray', linestyle='--', alpha=0.5)
plt.axvline(x=2, color='gray', linestyle='--', alpha=0.5)
