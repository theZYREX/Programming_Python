# 2. В лотерее разыгрывается мотоцикл стоимостью 250 рублей, велосипед стоимость 50 рублей и часы ценой 40 рублей.
# Найти математическое ожидание выигрыша для лица, имеющего один билет, если общее число билетов равно 100.

total_tickets = 100  #Общее число билетов

prizes = [250, 50, 40] # Стоимость выигрышей

p_win = 1 / total_tickets # Вероятность выиграть конкретный приз (1 билет из 100)

# Математическое ожидание дискретной случайной величины: M[X] = Σ (x_i * p_i)
# x_i - стоимость выигрыша, p_i - вероятность этого выигрыша.
# Также существует вероятность выиграть 0 рублей, но 0 * p = 0, поэтому это слагаемое можно не писать.

answer2 = 0
for prize in prizes:
    answer2 += prize * p_win

print(f"Ответ к задаче 2: {answer2}") # 3.4
