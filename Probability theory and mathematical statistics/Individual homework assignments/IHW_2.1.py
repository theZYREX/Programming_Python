# 1. Вероятность отказа детали за время испытания на надежность равна 0,2.
# Найти математическое ожидание числа отказавших деталей, если испытанию будут подвергнуты 10 деталей.

n1 = 10         # Количество испытываемых деталей
p1 = 0.2        # Вероятность отказа одной детали

# Так как испытания независимы и вероятность постоянна, это схема Бернулли.
# Математическое ожидание биномиального распределения вычисляется по формуле: M[X] = n * p
answer1 = n1 * p1

print(f"Ответ к задаче 1: {answer1}") # 2.0

