import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import scipy.stats as stats
from scipy import stats as sp_stats

# ВВОД ДАННЫХ
data = {
    'Страна': ['Австрия', 'Австралия', 'Белоруссия', 'Бельгия', 'Великобритания',
               'Германия', 'Дания', 'Индия', 'Испания', 'Италия', 'Канада',
               'Казахстан', 'Китай', 'Латвия', 'Нидерланды', 'Норвегия',
               'Польша', 'Россия', 'США', 'Украина', 'Финляндия',
               'Франция', 'Чехия', 'Швейцария', 'Швеция'],
    'y': [0.904, 0.922, 0.763, 0.923, 0.918, 0.906, 0.905, 0.545, 0.894, 0.9,
          0.932, 0.74, 0.701, 0.744, 0.921, 0.927, 0.802, 0.747, 0.927, 0.721,
          0.913, 0.918, 0.833, 0.914, 0.923],
    'x': [115, 123, 74, 111, 113, 110, 119, 146, 113, 108, 113, 71, 210, 94,
          118, 130, 127, 61, 117, 46, 107, 110, 99.2, 101, 105]
}

df = pd.DataFrame(data)
x = np.array(data['x'])
y = np.array(data['y'])
n = len(x)

print("=" * 70)
print("КОРРЕЛЯЦИОННО-РЕГРЕССИОННЫЙ АНАЛИЗ")
print("=" * 70)
print(f"\nКоличество наблюдений: n = {n}")

# ============================================================================
# 1. ПОСТРОИТЬ ПОЛЕ КОРРЕЛЯЦИИ
# ============================================================================
print("\n1. ПОЛЕ КОРРЕЛЯЦИИ")
print("-" * 70)

plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='blue', s=100, alpha=0.6, edgecolors='black', linewidth=1)
plt.xlabel('ВВП 1997 г., % к 1990 г. (x)', fontsize=12)
plt.ylabel('Индекс человеческого развития (y)', fontsize=12)
plt.title('Поле корреляции: Зависимость ИЧР от ВВП', fontsize=14, fontweight='bold')
plt.grid(True, alpha=0.3)

# Подписываем точки названиями стран (Шаг 1)
for i, country in enumerate(df['Страна']):
    plt.annotate(country, (x[i], y[i]), fontsize=8, alpha=0.7)

plt.tight_layout()
plt.show()

print("Гипотеза о форме связи:")
print("✓ Наблюдается ОТРИЦАТЕЛЬНАЯ линейная связь (с ростом x значение y падает)")
print()

# ============================================================================
# 2. УРАВНЕНИЕ РЕГРЕССИИ (С ПОДПИСЯМИ!)
# ============================================================================
print("2. РАСЧЕТ ПАРАМЕТРОВ УРАВНЕНИЯ РЕГРЕССИИ")
print("-" * 70)

# Расчет средних
x_mean = np.mean(x)
y_mean = np.mean(y)

# Расчет коэффициентов регрессии
numerator = np.sum((x - x_mean) * (y - y_mean))
denominator = np.sum((x - x_mean) ** 2)

b = numerator / denominator  # коэффициент регрессии (наклон)
a = y_mean - b * x_mean      # свободный член (пересечение с осью Y)

print(f"Уравнение регрессии в явном виде:")
print(f"y = {a:.4f} {'+' if b < 0 else '-'} {abs(b):.4f} * x")

# Построение линии регрессии
y_pred = a + b * x

plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='blue', s=80, alpha=0.6, edgecolors='black', linewidth=1, label='Эмпирические данные')
plt.plot(x, y_pred, color='red', linewidth=2, label=f'Линия регрессии\ny = {a:.3f} {b:+.3f}x')

# --- НОВОЕ: Подписываем точки названиями стран и на втором графике ---
for i, country in enumerate(df['Страна']):
    plt.annotate(country, (x[i], y[i]), fontsize=9, alpha=0.8)

plt.xlabel('ВВП 1997 г., % к 1990 г. (x)', fontsize=12)
plt.ylabel('Индекс человеческого развития (y)', fontsize=12)
plt.title('Линия регрессии', fontsize=14, fontweight='bold')
plt.legend(fontsize=11)
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ============================================================================
# 3. КОЭФФИЦИЕНТ ЛИНЕЙНОЙ КОРРЕЛЯЦИИ
# ============================================================================
print("3. КОЭФФИЦИЕНТ ЛИНЕЙНОЙ КОРРЕЛЯЦИИ")
print("-" * 70)

r = numerator / (np.sqrt(denominator * np.sum((y - y_mean) ** 2)))
r_squared = r ** 2

print(f"Коэффициент корреляции Пирсона r: {r:.6f}")
print(f"Коэффициент детерминации R²: {r_squared:.6f}")

if abs(r) >= 0.7:
    print(f"→ Сильная {'отрицательная' if r < 0 else 'положительная'} связь")
elif abs(r) >= 0.3:
    print(f"→ Умеренная {'отрицательная' if r < 0 else 'положительная'} связь")
else:
    print(f"→ Слабая {'отрицательная' if r < 0 else 'положительная'} связь")
print()

# ============================================================================
# 4. ОЦЕНКА ПАРАМЕТРОВ (t-критерий Стьюдента)
# ============================================================================
print("4. ОЦЕНКА ПАРАМЕТРОВ (t-критерий)")
print("-" * 70)

SS_res = np.sum((y - y_pred) ** 2)
s_e = np.sqrt(SS_res / (n - 2))

s_b = s_e / np.sqrt(denominator)
s_a = s_e * np.sqrt(1/n + x_mean**2 / denominator)

t_b = b / s_b
t_a = a / s_a

alpha = 0.05
df = n - 2
t_crit = sp_stats.t.ppf(1 - alpha/2, df)

print(f"Коэффициент b: t-статистика = {t_b:.4f}, критическое значение = {t_crit:.4f}")
print(f"Результат: коэффициент b {'ЗНАЧИМ' if abs(t_b) > t_crit else 'НЕ ЗНАЧИМ'}")

print(f"Коэффициент a: t-статистика = {t_a:.4f}, критическое значение = {t_crit:.4f}")
print(f"Результат: коэффициент a {'ЗНАЧИМ' if abs(t_a) > t_crit else 'НЕ ЗНАЧИМ'}")
print()

# ============================================================================
# 5. F-КРИТЕРИЙ ФИШЕРА
# ============================================================================
print("5. ОЦЕНКА УРАВНЕНИЯ (F-критерий Фишера)")
print("-" * 70)

F_calc = (r_squared / 1) / ((1 - r_squared) / (n - 2))
F_crit = sp_stats.f.ppf(1 - alpha, 1, n - 2)

print(f"F_расч = {F_calc:.4f}")
print(f"F_кр = {F_crit:.4f}")

if F_calc > F_crit:
    print("✓ Уравнение регрессии СТАТИСТИЧЕСКИ ЗНАЧИМО")
else:
    print(" Уравнение регрессии НЕ ЗНАЧИМО")

print("\n" + "=" * 70)
